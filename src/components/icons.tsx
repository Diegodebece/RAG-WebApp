// Claude's spark, drawn as rays of slightly different lengths around a center.
const CLAUDE_RAYS = Array.from({ length: 12 }, (_, i) => {
  const angle = (i * Math.PI) / 6 + (i % 2 ? 0.12 : 0)
  const length = i % 3 === 0 ? 10.5 : i % 3 === 1 ? 8.5 : 9.5
  const point = (r: number) => `${(12 + Math.cos(angle) * r).toFixed(2)} ${(12 + Math.sin(angle) * r).toFixed(2)}`
  return `M${point(1.5)}L${point(length)}`
}).join('')

export function ClaudeIcon() {
  return (
    <svg viewBox="0 0 24 24" fill="none" stroke="#d97757" strokeWidth="2.4" strokeLinecap="round" aria-hidden="true">
      <path d={CLAUDE_RAYS} />
    </svg>
  )
}

